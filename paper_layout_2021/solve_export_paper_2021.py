# -*- coding: utf-8 -*-
# Run INSIDE HFSS 2021 R1, after build_paper_layout_2021.py, with its design active.
# This script runs a solver and may take considerable time and memory.
import os
import time
import traceback
import ScriptEnv


def run():
    ScriptEnv.Initialize('Ansoft.ElectronicsDesktop')
    desktop = oDesktop
    project = desktop.GetActiveProject()
    if project is None:
        raise RuntimeError('Open the project generated by build_paper_layout_2021.py first.')
    design = project.GetActiveDesign()
    if design is None or design.GetName().split(';')[-1] != 'Fig2d_paper_layout_2021':
        raise RuntimeError('Activate Fig2d_paper_layout_2021 before running this script.')
    output = os.path.join(project.GetPath(), 'results_' + time.strftime('%Y%m%d_%H%M%S'))
    if os.path.exists(output):
        raise RuntimeError('Result directory already exists; wait a second and retry.')
    os.makedirs(output)
    log = open(os.path.join(output, 'solve_export_log.txt'), 'w')
    try:
        if design.ValidateDesign(os.path.join(output, 'validation.log')) != 1:
            raise RuntimeError('Design validation failed. Inspect validation.log.')
        log.write('Starting Setup220: adaptive solution plus both sweeps.\n')
        log.flush()
        project.Save()
        # Uses the HFSS analysis configuration already set on this computer.
        # No HPC core count or license setting is forced by the script.
        design.Analyze('Setup220')
        project.Save()
        report = design.GetModule('ReportSetup')
        stamp = time.strftime('%H%M%S')
        families = ['Freq:=', ['All']]
        expressions = [
            ('S11', ['dB(S(Graphene,Graphene))']),
            ('Zin', ['re(Z(Graphene,Graphene))', 'im(Z(Graphene,Graphene))'])]
        for sweep in ('Sweep100_220', 'CheckDiscrete'):
            for quantity, traces in expressions:
                name = quantity + '_' + sweep + '_' + stamp
                report.CreateReport(name, 'Modal Solution Data', 'Rectangular Plot',
                    'Setup220 : ' + sweep, ['Domain:=', 'Sweep'], families,
                    ['X Component:=', 'Freq', 'Y Component:=', traces])
                report.ExportToFile(name, os.path.join(output, quantity + '_' + sweep + '.csv'), False)
        # Preserve underlying complex S11 for independent checks and conversion.
        report.CreateReport('ComplexS11_' + stamp, 'Modal Solution Data', 'Rectangular Plot',
            'Setup220 : Sweep100_220', ['Domain:=', 'Sweep'], families,
            ['X Component:=', 'Freq', 'Y Component:=',
             ['re(S(Graphene,Graphene))', 'im(S(Graphene,Graphene))']])
        report.ExportToFile('ComplexS11_' + stamp, os.path.join(output, 'ComplexS11.csv'), False)
        project.Save()
        log.write('Reports exported to: ' + output + '\n')
        log.write('Check adaptive convergence and discrete points before accepting results.\n')
        desktop.AddMessage('', '', 0, 'Reports exported: ' + output +
            '. Review adaptive convergence; export success is not a convergence test.')
    except Exception:
        detail = traceback.format_exc()
        log.write(detail)
        desktop.AddMessage('', '', 2, 'Solve/export failed. See ' + output + '\n' + detail)
        raise
    finally:
        log.close()


run()
